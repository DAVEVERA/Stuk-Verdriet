## Praktische hulp bij ziekte

Tijdens een ziekteproces kan praktische steun gaan over medische gesprekken, vervoer, werk, school, zorg thuis, kinderopvang, maaltijden, administratie en contact met familie of vrienden. Het helpt om vooraf vragen op te schrijven voor artsen of verpleegkundigen. Neem iemand mee naar belangrijke gesprekken als dat kan. Twee mensen onthouden meer dan één, zeker wanneer spanning hoog is.

Bij kanker of langdurige ziekte kunnen onderwerpen zoals werk en inkomen, studie, vruchtbaarheid, mantelzorg, palliatieve zorg en mentale ondersteuning belangrijk worden. Niet alles hoeft in één gesprek. Vraag zorgverleners wie jou bij welk onderwerp kan helpen. Soms is er een verpleegkundig specialist, maatschappelijk werker, AYA-zorgverlener, bedrijfsarts of patiëntenorganisatie die overzicht kan bieden.

Laat ook kleine vormen van hulp toe. Een maaltijd, vervoer, oppas, een boodschap, een appje naar de familie, een was draaien: het zijn geen details als jij daardoor even kunt ademen.

## Praktische hulp na overlijden

Na een overlijden komt er vaak veel tegelijk op je af. Afscheid, uitvaart, administratieve zaken, werk, bankzaken, verzekeringen, woning, digitale accounts, abonnementen, nalatenschap en persoonlijke spullen. Sommige dingen zijn wettelijk of praktisch nodig. Andere dingen voelen vooral emotioneel zwaar.

Het kan helpen om keuzes te verdelen. Wie belt instanties? Wie bewaart documenten? Wie houdt een lijst bij van mensen die geïnformeerd zijn? Wie zorgt voor eten op drukke dagen? Wie kan mee naar afspraken? Als mensen vragen wat ze kunnen doen, geef dan concrete taken. "Kun je dinsdag boodschappen brengen?" is makkelijker uit te voeren dan "we laten wel weten als we iets nodig hebben."

Wees voorzichtig met grote beslissingen wanneer die kunnen wachten. Spullen opruimen, een woning veranderen, foto's uitzoeken of digitale berichten verwijderen kan veel losmaken. Je hoeft niet direct te weten wat goed voelt. Soms is bewaren voorlopig de beste keuze.

